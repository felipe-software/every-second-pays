import { createPillJellyGesture, type PillJellyGestureInputs } from "../utils/pill-jelly-gesture";
import { useMemo } from "react";

// RNGH serializes every worklet of a new gesture to the UI runtime, so rebuild only on input changes.
export const usePillJellyGesture = (inputs: PillJellyGestureInputs) =>
    useMemo(
        () =>
            createPillJellyGesture({
                beginTabbarInteraction: inputs.beginTabbarInteraction,
                confirmTabPressOnJS: inputs.confirmTabPressOnJS,
                downX: inputs.downX,
                dragStartPanelOffset: inputs.dragStartPanelOffset,
                dragStartTarget: inputs.dragStartTarget,
                endTabbarInteraction: inputs.endTabbarInteraction,
                isDragging: inputs.isDragging,
                movedDistance: inputs.movedDistance,
                onTabLongPress: inputs.onTabLongPress,
                pillJelly: inputs.pillJelly,
                pressTarget: inputs.pressTarget,
                progressOwnedByTabBar: inputs.progressOwnedByTabBar,
                rawPanelOffset: inputs.rawPanelOffset,
                rawPanelOffsetVelocity: inputs.rawPanelOffsetVelocity,
                recording: inputs.recording,
                releasePending: inputs.releasePending,
                setFrameLoopActive: inputs.setFrameLoopActive,
                shapeTarget: inputs.shapeTarget,
                tabCount: inputs.tabCount,
                targetValue: inputs.targetValue,
                trackHeight: inputs.trackHeight,
                trackInset: inputs.trackInset,
                trackWidth: inputs.trackWidth,
                updateDistortion: inputs.updateDistortion,
                webTrackPageX: inputs.webTrackPageX,
            }),
        [
            inputs.beginTabbarInteraction,
            inputs.confirmTabPressOnJS,
            inputs.downX,
            inputs.dragStartPanelOffset,
            inputs.dragStartTarget,
            inputs.endTabbarInteraction,
            inputs.isDragging,
            inputs.movedDistance,
            inputs.onTabLongPress,
            inputs.pillJelly,
            inputs.progressOwnedByTabBar,
            inputs.rawPanelOffset,
            inputs.rawPanelOffsetVelocity,
            inputs.recording,
            inputs.releasePending,
            inputs.pressTarget,
            inputs.setFrameLoopActive,
            inputs.shapeTarget,
            inputs.tabCount,
            inputs.targetValue,
            inputs.trackHeight,
            inputs.trackInset,
            inputs.trackWidth,
            inputs.updateDistortion,
            inputs.webTrackPageX,
        ],
    );
