const kotlinSlot = (spec) =>
    `AmbientSlot(size = ${spec.size}f, alpha = ${spec.alpha}f, rotation = ${spec.rotation}f, vx = ${spec.vx ?? 0}f, vy = ${spec.vy ?? 0}f, spin = ${spec.spin ?? 0}f, radius = ${spec.radius ?? 0}f, phase = ${spec.phase}f)`;

const auroraIds = (prefix, { aurora, AURORA_DIRECTIONS, AURORA_PULSES }) =>
    aurora
        .map(
            (_, index) =>
                `    listOf(${Object.keys(AURORA_DIRECTIONS)
                    .map(
                        (d) =>
                            `intArrayOf(${Object.keys(AURORA_PULSES)
                                .map((v) => `R.id.${prefix}${index}${d}${v}`)
                                .join(", ")})`,
                    )
                    .join(", ")}),`,
        )
        .join("\n");

export const moneyEffectsKotlin = ({ ambient, aurora, UNIT, IMPACT, AURORA_DIRECTIONS, AURORA_PULSES }) =>
    `package expo.modules.notificationmotion.money

// Generated by scripts/generate-money-widget-resources.mjs. Do not edit.

import expo.modules.notificationmotion.R

internal class AmbientSlot(
  val size: Float,
  val alpha: Float,
  val rotation: Float,
  val vx: Float,
  val vy: Float,
  val spin: Float,
  val radius: Float,
  val phase: Float,
)

internal object MoneyEffects {
  const val UNIT = ${UNIT}f
  const val IMPACT = ${IMPACT}
  val slots: Map<String, List<AmbientSlot>> = mapOf(
${Object.entries(ambient)
    .map(
        ([name, slots]) =>
            `    "${name}" to listOf(\n${slots.map((spec) => `      ${kotlinSlot(spec)},`).join("\n")}\n    ),`,
    )
    .join("\n")}
  )
}

internal class AuroraBlob(
  val size: Float,
  val baseX: Float,
  val baseY: Float,
  val dirX: Float,
  val dirY: Float,
  val amplitude: Float,
  val leg: Float,
  val phase: Float,
  val deep: Boolean,
)

internal object MoneyAurora {
  val blobs = listOf(
${aurora.map((blob) => `    AuroraBlob(size = ${blob.size}f, baseX = ${blob.baseX}f, baseY = ${blob.baseY}f, dirX = ${blob.dirX}f, dirY = ${blob.dirY}f, amplitude = ${blob.amplitude}f, leg = ${blob.leg}f, phase = ${blob.phase}f, deep = ${blob.tone === "deep"}),`).join("\n")}
  )
  val containers: List<List<IntArray>> = listOf(
${auroraIds("nmw_au", { aurora, AURORA_DIRECTIONS, AURORA_PULSES })}
  )
  val images: List<List<IntArray>> = listOf(
${auroraIds("nmw_aui", { aurora, AURORA_DIRECTIONS, AURORA_PULSES })}
  )
}
`;
