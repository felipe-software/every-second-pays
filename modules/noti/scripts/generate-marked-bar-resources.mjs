import { markedBarTablesKotlin } from "./marked-bar-kotlin.mjs";
import {
    addLayouts,
    billBody,
    box,
    flashFace,
    flipper,
    OPEN,
    pieceImage,
    PLACEHOLDER,
    sparkBody,
} from "./marked-bar-layouts.mjs";
import { billPiece, flashAnim, ringAnim, scaleBy, sparkPiece } from "./marked-bar-pieces.mjs";
import {
    alpha,
    createResources,
    i,
    NS,
    readOutputDirectories,
    round,
    scale,
    translate,
    writeKotlinFile,
    writeResourceFiles,
} from "./resource-xml.mjs";

const { root, kotlinRoot } = readOutputDirectories("generate-marked-bar-resources.mjs");
const resources = createResources("<!-- Generated by scripts/generate-marked-bar-resources.mjs. Do not edit. -->\n");
const { files, write, anim } = resources;

const LEAD = 380;
const DURATIONS = { short: 620, chain: 900 };
const arrival = (set) => LEAD + DURATIONS[set];
const LIGHT_GRID = 80;
const LIGHT_STEPS = Array.from({ length: Math.ceil(DURATIONS.chain / LIGHT_GRID) + 1 }, (_, step) => step);
const MINI_MARKS = [25, 50, 75, 90];
const MAX_REELS = 12;
const BLAST = { short: { bills: 20, sparks: 14 }, chain: { bills: 22, sparks: 16 } };
const MINI_BILLS = 3;
const MINI_SPARKS = 4;
const reelLines = (index) => Math.min(15, 6 + index * 2) + 1;
const smooth = (t) => t * t * (3 - 2 * t);
const invert = (f, goal) => {
    let low = 0;
    let high = 1;
    for (let step = 0; step < 22; step += 1) {
        const middle = (low + high) / 2;
        if (f(middle) < goal) low = middle;
        else high = middle;
    }
    return low;
};

const interpolators = {
    nmb_i_ease: `<pathInterpolator ${NS} android:controlX1="0.4" android:controlY1="0" android:controlX2="0.6" android:controlY2="1" />`,
    nmb_i_reel: `<pathInterpolator ${NS} android:controlX1="0.12" android:controlY1="0.72" android:controlX2="0.24" android:controlY2="1.02" />`,
    nmb_i_out: `<decelerateInterpolator ${NS} android:factor="1.3" />`,
    nmb_i_out_hard: `<decelerateInterpolator ${NS} android:factor="1.5" />`,
    nmb_i_soft: `<decelerateInterpolator ${NS} android:factor="1" />`,
    nmb_i_fall: `<accelerateInterpolator ${NS} android:factor="1" />`,
    nmb_i_linear: `<linearInterpolator ${NS} />`,
    nmb_i_spring: `<overshootInterpolator ${NS} android:tension="1.4" />`,
};
for (const [name, body] of Object.entries(interpolators)) write(`interpolator/${name}.xml`, body);

for (const step of LIGHT_STEPS) {
    const at = LEAD + step * LIGHT_GRID;
    anim(`nmb_hot_${step}`, [
        alpha({ fromAlpha: 0, toAlpha: 1, startOffset: at, duration: 130, interpolator: i("nmb_i_linear") }),
    ]);
    anim(`nmb_pop_${step}`, [
        scaleBy(1, 1.4, [at, 120, "nmb_i_soft"]),
        scaleBy(1, 0.714, [at + 120, 310, "nmb_i_soft"]),
    ]);
}

const GOLDEN = 0.618034;
const spread = (index, from, to) => from + (to - from) * ((index * GOLDEN + 0.13) % 1);

const FULL = [0, Math.PI * 2];
const UP = [-Math.PI * 1.02, Math.PI * 0.02];
const blastTables = {};
for (const set of Object.keys(DURATIONS)) {
    const at = arrival(set);
    const [from, to] = set === "chain" ? FULL : UP;
    const bills = Array.from({ length: BLAST[set].bills }, (_, index) =>
        billPiece(anim, `nmb_${set}_bill_${index}`, spread(index, from, to), at),
    );
    const sparks = Array.from({ length: BLAST[set].sparks }, (_, index) =>
        sparkPiece(anim, `nmb_${set}_spark_${index}`, spread(index, from, to), at),
    );
    blastTables[set] = { bills, sparks };
    flashAnim(anim, `nmb_${set}_flash`, at);
    ringAnim(anim, `nmb_${set}_ring0`, at, 600);
    ringAnim(anim, `nmb_${set}_ring1`, at + 110, 720);
    write(
        `layout/nmb_blast_${set}.xml`,
        box(
            [
                ...bills.map((piece, index) => billBody(index, `nmb_${set}_bill_${index}`, piece)),
                ...sparks.map((piece, index) => sparkBody(index, `nmb_${set}_spark_${index}`, piece)),
            ].join("\n    "),
        ),
    );
    write(
        `layout/nmb_burst_${set}.xml`,
        box(
            [
                flipper("nmb_flash", `nmb_${set}_flash`, flashFace),
                flipper("nmb_ring0", `nmb_${set}_ring0`, pieceImage("nmb_ring0i", "nmb_ring")),
                flipper("nmb_ring1", `nmb_${set}_ring1`, pieceImage("nmb_ring1i", "nmb_ring")),
            ].join("\n    "),
        ),
    );
}

const MINI_UP = [-Math.PI * 0.95, -Math.PI * 0.05];
const miniTables = {};
for (const mark of MINI_MARKS) {
    const at = LEAD + round(invert(smooth, mark / 100) * DURATIONS.chain, 0);
    const bills = Array.from({ length: MINI_BILLS }, (_, index) =>
        billPiece(anim, `nmb_mini_${mark}_bill_${index}`, spread(index, ...MINI_UP), at),
    );
    const sparks = Array.from({ length: MINI_SPARKS }, (_, index) =>
        sparkPiece(anim, `nmb_mini_${mark}_spark_${index}`, spread(index + 1, ...MINI_UP), at),
    );
    miniTables[mark] = { bills, sparks };
    flashAnim(anim, `nmb_mini_${mark}_flash`, at);
    ringAnim(anim, `nmb_mini_${mark}_ring`, at, 600);
    write(
        `layout/nmb_mini_${mark}.xml`,
        box(
            [
                ...bills.map((piece, index) => billBody(index, `nmb_mini_${mark}_bill_${index}`, piece)),
                ...sparks.map((piece, index) => sparkBody(index, `nmb_mini_${mark}_spark_${index}`, piece)),
            ].join("\n    "),
        ),
    );
    write(
        `layout/nmb_miniburst_${mark}.xml`,
        box(
            [
                flipper("nmb_flash", `nmb_mini_${mark}_flash`, flashFace),
                flipper("nmb_ring0", `nmb_mini_${mark}_ring`, pieceImage("nmb_ring0i", "nmb_ring")),
            ].join("\n    "),
        ),
    );
}

for (const set of Object.keys(DURATIONS)) {
    const arrive = arrival(set);
    for (let index = 0; index < MAX_REELS; index += 1) {
        const lines = reelLines(index);
        anim(`nmb_reel_${set}_${index}`, [
            translate({
                fromYDelta: `${round(((lines - 1) / lines) * 100, 2)}%`,
                toYDelta: "0",
                startOffset: LEAD + 40,
                duration: Math.max(120, DURATIONS[set] + 20 + index * 46 - 40),
                interpolator: i("nmb_i_reel"),
            }),
        ]);
        write(
            `layout/nmb_reel_${set}_${index}.xml`,
            `<FrameLayout ${NS} android:id="@+id/nmb_reel_box" android:layout_width="wrap_content" android:layout_height="20dp" android:clipChildren="true" android:clipToPadding="true">
    <ViewFlipper android:id="@+id/nmb_reel" android:layout_width="wrap_content" android:layout_height="match_parent" android:inAnimation="@anim/nmb_reel_${set}_${index}" ${OPEN}>
        ${PLACEHOLDER}
        <TextView android:id="@+id/nmb_reel_text" android:layout_width="wrap_content" android:layout_height="100dp" android:layout_gravity="bottom" android:fontFamily="sans-serif" android:textStyle="bold" android:fontFeatureSettings="tnum" android:letterSpacing="-0.02" android:gravity="bottom|center_horizontal" android:includeFontPadding="false" android:textColor="#FFFFFFFF" />
    </ViewFlipper>
</FrameLayout>`,
        );
    }
    const peaks = set === "chain" ? [1.2] : [1.09, 1.12, 1.16];
    peaks.forEach((peak, level) => {
        anim(`nmb_bump_${set}_${level}`, [
            scaleBy(1, peak, [arrive, 112, "nmb_i_spring"]),
            scaleBy(1, round(1 / peak, 4), [arrive + 112, 448, "nmb_i_soft"]),
        ]);
        write(
            `layout/nmb_amount_${set}_${level}.xml`,
            `<ViewFlipper ${NS} android:id="@+id/nmb_bump" android:layout_width="wrap_content" android:layout_height="wrap_content" android:layout_gravity="center_horizontal|top" android:inAnimation="@anim/nmb_bump_${set}_${level}" ${OPEN}>
    ${PLACEHOLDER}
    <LinearLayout android:id="@+id/nmb_amount_row" android:layout_width="wrap_content" android:layout_height="wrap_content" android:baselineAligned="false" android:orientation="horizontal" ${OPEN} />
</ViewFlipper>`,
        );
    });
    const rest = 0.274;
    anim(`nmb_pulse_${set}`, [
        alpha({ fromAlpha: rest, toAlpha: rest, duration: arrive + 900, interpolator: i("nmb_i_linear") }),
        alpha({
            fromAlpha: 1,
            toAlpha: round(1 / rest, 3),
            startOffset: arrive,
            duration: 180,
            interpolator: i("nmb_i_soft"),
        }),
        alpha({ fromAlpha: 1, toAlpha: rest, startOffset: arrive + 180, duration: 720, interpolator: i("nmb_i_soft") }),
        scaleBy(1, 1.3, [arrive, 180, "nmb_i_soft"]),
        scaleBy(1, 0.769, [arrive + 180, 720, "nmb_i_soft"]),
    ]);
    anim(`nmb_fill_${set}`, [
        scale({
            fromXScale: 0,
            toXScale: 1,
            fromYScale: 1,
            toYScale: 1,
            pivotX: "0%",
            startOffset: LEAD,
            duration: DURATIONS[set],
            interpolator: i("nmb_i_ease"),
        }),
    ]);
    write(
        `layout/nmb_fill_${set}.xml`,
        `<FrameLayout ${NS} android:id="@+id/nmb_fill_box" android:layout_width="10dp" android:layout_height="match_parent" android:layout_gravity="left">
    ${flipper("nmb_fill_trigger", `nmb_fill_${set}`, '<ImageView android:id="@+id/nmb_fill_face" android:layout_width="match_parent" android:layout_height="match_parent" android:importantForAccessibility="no" android:scaleType="fitXY" android:src="@drawable/nmb_solid" />')}
</FrameLayout>`,
    );
}

const shake = [
    [1.6, -1.8],
    [-3, 2.8],
    [2.1, -0.7],
    [-1.5, -1.2],
    [0.8, 0.9],
];
anim(
    "nmb_shake",
    shake.map(([x, y], index) =>
        translate({
            fromXDelta: "0",
            toXDelta: `${x}%`,
            fromYDelta: "0",
            toYDelta: `${y}%`,
            startOffset: arrival("chain") + index * 68,
            duration: 68,
            interpolator: i("nmb_i_linear"),
        }),
    ),
);

addLayouts(resources, LIGHT_STEPS);

writeResourceFiles(root, files);
writeKotlinFile(
    kotlinRoot,
    "expo/modules/notificationmotion/bills",
    "MarkedBarTables.kt",
    markedBarTablesKotlin({
        DURATIONS,
        LIGHT_GRID,
        MAX_REELS,
        LIGHT_STEPS,
        MINI_MARKS,
        reelLines,
        blastTables,
        miniTables,
    }),
);
console.log(`Wrote ${Object.keys(files).length} marked bar resources.`);
