let seed = 0xb111;
const random = () => {
    seed = (seed * 1103515245 + 12345) & 0x7fffffff;
    return seed / 0x7fffffff;
};
const between = (min, max) => min + random() * (max - min);
const round = (value, digits = 2) => Number(value.toFixed(digits));
const percent = (value) => `${round(value * 100, 1)}%p`;

const LEAD = 380;
