import { addAmbientAnimations, ambient, UNIT } from "./money-widget-ambient.mjs";
import {
    addAuroraAnimations,
    addAuroraLayout,
    aurora,
    AURORA_DIRECTIONS,
    AURORA_PULSES,
} from "./money-widget-aurora.mjs";
import { moneyEffectsKotlin } from "./money-widget-kotlin.mjs";
import { addLayouts } from "./money-widget-layouts.mjs";
import { addFlightAnimations, addMotionAnimations, IMPACT } from "./money-widget-motions.mjs";
import {
    alpha,
    createResources,
    i,
    NS,
    readOutputDirectories,
    scale,
    writeKotlinFile,
    writeResourceFiles,
} from "./resource-xml.mjs";

const { root, kotlinRoot } = readOutputDirectories("generate-money-widget-resources.mjs");
const resources = createResources("<!-- Generated by scripts/generate-money-widget-resources.mjs. Do not edit. -->\n");
const { files, write, anim } = resources;

const interpolators = {
    nmw_i_overshoot: `<overshootInterpolator ${NS} android:tension="1.6" />`,
    nmw_i_overshoot_soft: `<overshootInterpolator ${NS} android:tension="0.9" />`,
    nmw_i_bounce: `<bounceInterpolator ${NS} />`,
    nmw_i_decelerate: `<decelerateInterpolator ${NS} android:factor="1.8" />`,
    nmw_i_decelerate_hard: `<decelerateInterpolator ${NS} android:factor="3" />`,
    nmw_i_accelerate: `<accelerateInterpolator ${NS} android:factor="1.6" />`,
    nmw_i_gravity: `<accelerateInterpolator ${NS} android:factor="1.25" />`,
    nmw_i_ease: `<accelerateDecelerateInterpolator ${NS} />`,
    nmw_i_cubic: `<pathInterpolator ${NS} android:controlX1="0.65" android:controlY1="0" android:controlX2="0.35" android:controlY2="1" />`,
    nmw_i_linear: `<linearInterpolator ${NS} />`,
    nmw_i_bow: `<cycleInterpolator ${NS} android:cycles="0.5" />`,
    nmw_i_arc_high: `<pathInterpolator ${NS} android:pathData="M0,0 C0.18,-3.4 0.42,-3.4 1,1" />`,
    nmw_i_arc_low: `<pathInterpolator ${NS} android:pathData="M0,0 C0.2,-2.6 0.45,-2.6 1,1" />`,
    nmw_i_lob: `<pathInterpolator ${NS} android:pathData="M0,0 C0.3,0.85 0.55,1.18 1,1" />`,
    nmw_i_late: `<pathInterpolator ${NS} android:pathData="M0,0 L0.72,0 L1,1" />`,
    nmw_i_last: `<pathInterpolator ${NS} android:pathData="M0,0 L0.86,0 L1,1" />`,
};
for (const [name, body] of Object.entries(interpolators)) write(`interpolator/${name}.xml`, body);

const loop = (extra = {}) => ({ repeatCount: "-1", repeatMode: "restart", ...extra });

addMotionAnimations(resources);
addAmbientAnimations(resources);
addFlightAnimations(resources);
addAuroraAnimations(resources);

anim(
    "nmw_p_live",
    [
        alpha({
            fromAlpha: 1,
            toAlpha: 0.45,
            duration: 900,
            interpolator: i("nmw_i_ease"),
            ...loop({ repeatMode: "reverse" }),
        }),
    ],
    { fillAfter: false },
);
anim(
    "nmw_p_halo",
    [
        scale({
            fromXScale: 0.4,
            toXScale: 1,
            fromYScale: 0.4,
            toYScale: 1,
            duration: 1500,
            interpolator: i("nmw_i_decelerate"),
            ...loop(),
        }),
        alpha({ fromAlpha: 0.7, toAlpha: 0, duration: 1500, interpolator: i("nmw_i_decelerate"), ...loop() }),
    ],
    { fillAfter: false },
);

write(
    "animator/nmw_instant_in.xml",
    `<objectAnimator ${NS} android:propertyName="alpha" android:valueFrom="1" android:valueTo="1" android:duration="0" />`,
);
write(
    "animator/nmw_instant_out.xml",
    `<objectAnimator ${NS} android:propertyName="alpha" android:valueFrom="0" android:valueTo="0" android:duration="0" />`,
);

write(
    "drawable/nmw_widget_bg.xml",
    `<shape ${NS} android:shape="rectangle"><solid android:color="#FFFFFFFF" /><corners android:radius="@android:dimen/system_app_widget_background_radius" /></shape>`,
);
write("drawable/nmw_dot.xml", `<shape ${NS} android:shape="oval"><solid android:color="#FFFFFFFF" /></shape>`);
write(
    "drawable/nmw_glow_blob.xml",
    `<shape ${NS} android:shape="oval"><gradient android:type="radial" android:gradientRadius="50%" android:startColor="#FFFFFFFF" android:centerColor="#55FFFFFF" android:endColor="#00FFFFFF" /></shape>`,
);

addAuroraLayout(resources);
addLayouts(resources);

writeResourceFiles(root, files);
writeKotlinFile(
    kotlinRoot,
    "expo/modules/notificationmotion/money",
    "MoneyEffects.kt",
    moneyEffectsKotlin({ ambient, aurora, UNIT, IMPACT, AURORA_DIRECTIONS, AURORA_PULSES }),
);
console.log(`Wrote ${Object.keys(files).length} resources.`);
