const wobbleWave = () => {
    const harmonics = [[1, 1, random()], [2, between(0.15, 0.4), random()]];
    const raw = (t) => harmonics.reduce((sum, [k, a, p]) => sum + a * Math.sin(2 * Math.PI * (k * t + p)), 0);
    const start = raw(0);
    return (t) => raw(t) - start;
};
// An interpolator can only run from 0 to 1, so a wobble plays as two animations of the same
// property: one along t + wave(t), and a linear one taking t back off.
const wobbleInterpolator = (name, wave) => {
    const f = (t) => t + wave(t);
    const slope = (t) => (f(t + 1e-4) - f(t - 1e-4)) / 2e-4;
    const steps = 12;
    const h = 1 / steps;
    const point = (x, y) => `${round(x, 4)},${round(y, 4)}`;
    let path = 'M0,0';
    for (let step = 0; step < steps; step++) {
        const x0 = step * h;
        const x1 = x0 + h;
        const y0 = step === 0 ? 0 : f(x0);
        const y1 = step === steps - 1 ? 1 : f(x1);
        path += ` C${point(x0 + h / 3, y0 + (slope(x0) * h) / 3)} ${point(x1 - h / 3, y1 - (slope(x1) * h) / 3)} ${point(x1, y1)}`;
    }
    write(`interpolator/${name}.xml`, `<pathInterpolator ${NS} android:pathData="${path}" />`);
    return i(name);
};
